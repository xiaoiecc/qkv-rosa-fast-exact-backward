@dataclass(frozen=True)
class _SharedRepairBridge:
    q_pos: int
    k_pos: int
    bit: int
    left: int
    right: int

    @property
    def end_t(self) -> int:
        return self.q_pos + self.right

    @property
    def q_priority(self) -> Tuple[int, int]:
        return (self.left, self.k_pos)

    @property
    def k_priority(self) -> Tuple[int, int]:
        return (self.left + 1 - self.q_pos, self.k_pos - self.q_pos)

    @property
    def shift(self) -> int:
        return self.k_pos - self.q_pos + 1

    def route_at(self, t: int) -> Route:
        d = int(t) - self.q_pos
        return (self.left + 1 + d, self.k_pos + d)

def _onebit_index(x: int, D: int) -> Optional[int]:
    x = int(x)
    if x <= 0 or x & x - 1:
        return None
    j = x.bit_length() - 1
    return j if j < D else None


@dataclass(frozen=True, order=True)
class _KRunRepairCertificate:
    """K-only current-endpoint H-ramp repair certificate.

    A maximal run [l,r] of minimal period q contributes periods p=k*q with 2p<=|run|.
    If the run breaks at r+1 by exactly one trainable bit, owner s=r-p+1 can repair every
    current-endpoint H-ramp anchor M in [m_lo,m_hi], selecting endpoint M-p.
    """
    owner: int
    period: int
    bit: int
    m_lo: int
    m_hi: int


def _next_suffix_rank_index(ranks: Sequence[int], *, smaller: bool) -> List[int]:
    """Next position to the right with smaller/greater suffix rank, via one monotone stack."""
    n = len(ranks)
    out = [n] * n
    st: List[int] = []
    for i in range(n - 1, -1, -1):
        ri = int(ranks[i])
        if smaller:
            while st and int(ranks[st[-1]]) >= ri:
                st.pop()
        else:
            while st and int(ranks[st[-1]]) <= ri:
                st.pop()
        out[i] = st[-1] if st else n
        st.append(i)
    return out


def _enumerate_k_runs_from_existing_lce(index: CausalCutSuffixIndex) -> List[Tuple[int, int, int]]:
    """Enumerate all maximal runs (left,right,minimal_period) using the existing K suffix ranks/LCEs.

    This is the two-Lyndon-orientation run characterization: next-smaller and next-greater K-suffix
    ranks provide the two candidate Lyndon roots.  Each candidate is maximally extended by one LCS
    and one LCP.  Duplicate reports from the two orientations are removed.
    """
    T = index.T
    if T <= 1:
        return []
    ranks = [int(index.fwd.rank[index.k_off + i]) for i in range(T)]
    runs = set()
    for smaller in (True, False):
        nxt = _next_suffix_rank_index(ranks, smaller=smaller)
        for i, j in enumerate(nxt):
            if j >= T:
                continue
            p = int(j - i)
            if p <= 0:
                continue
            if i <= 0:
                left_ext = 0
            else:
                left_ext = min(
                    i,
                    j,
                    index.rev.lcp_pos(index.rk_off + T - i, index.rk_off + T - j),
                )
            right_ext = min(
                T - i,
                T - j,
                index.fwd.lcp_pos(index.k_off + i, index.k_off + j),
            )
            if left_ext + right_ext < p:
                continue
            lo = int(i - left_ext)
            hi = int(j + right_ext - 1)
            if hi - lo + 1 < 2 * p:
                continue
            runs.add((lo, hi, p))
    return sorted(runs)


class _KRunRepairCertificateIndex:
    """Static (M point, owner interval) reporting index over O(T) run repair certificates.

    Certificates are interval-decomposed on the M axis into a segment tree.  A point M visits one
    root-to-leaf path; each bucket is owner-sorted, so query work is O(log^2 T + output).
    """

    def __init__(self, index: CausalCutSuffixIndex, D: int, stats: Optional[RepairStats]=None):
        self.T = int(index.T)
        self.stats = stats
        certs = set()
        runs = _enumerate_k_runs_from_existing_lce(index)
        if stats is not None:
            stats.k_run_count += len(runs)
        for lo, hi, q in runs:
            run_len = int(hi - lo + 1)
            max_k = run_len // (2 * int(q))
            if hi + 1 >= self.T:
                if stats is not None:
                    stats.k_run_period_candidates += max_k
                continue
            right_symbol_pos = hi + 1
            for mult in range(1, max_k + 1):
                p = int(mult * q)
                if stats is not None:
                    stats.k_run_period_candidates += 1
                s = int(hi - p + 1)
                j = _onebit_index(int(index.k[s]) ^ int(index.k[right_symbol_pos]), D)
                if j is None:
                    continue
                if right_symbol_pos + 1 >= self.T:
                    rho = 0
                else:
                    rho = min(
                        self.T - (s + 1),
                        self.T - (right_symbol_pos + 1),
                        index.fwd.lcp_pos(index.k_off + s + 1, index.k_off + right_symbol_pos + 1),
                    )
                m_lo = int(right_symbol_pos)
                m_hi = int(min(self.T - 1, right_symbol_pos + rho))
                certs.add(_KRunRepairCertificate(s, p, int(j), m_lo, m_hi))
        self.certs = sorted(certs)
        if stats is not None:
            stats.k_run_certificates += len(self.certs)

        size = 1
        while size < max(1, self.T):
            size <<= 1
        self.size = size
        rows: List[List[_KRunRepairCertificate]] = [[] for _ in range(2 * size)]
        entries = 0
        for c in self.certs:
            l = c.m_lo + size
            r = c.m_hi + 1 + size
            while l < r:
                if l & 1:
                    rows[l].append(c)
                    entries += 1
                    l += 1
                if r & 1:
                    r -= 1
                    rows[r].append(c)
                    entries += 1
                l >>= 1
                r >>= 1
        self.rows = []
        self.owners = []
        for row in rows:
            row.sort(key=lambda c: (c.owner, c.bit, c.period, c.m_lo, c.m_hi))
            self.rows.append(row)
            self.owners.append([c.owner for c in row])
        if stats is not None:
            stats.k_run_certificate_index_entries += entries

    def query(self, M: int, s_lo: int, s_hi: int) -> List[_KRunRepairCertificate]:
        M = int(M)
        s_lo = int(s_lo)
        s_hi = int(s_hi)
        if not (0 <= M < self.T) or s_lo > s_hi:
            return []
        if self.stats is not None:
            self.stats.k_run_certificate_queries += 1
        out: List[_KRunRepairCertificate] = []
        node = self.size + M
        while node:
            owners = self.owners[node]
            if owners:
                a = bisect.bisect_left(owners, s_lo)
                b = bisect.bisect_right(owners, s_hi)
                out.extend(self.rows[node][a:b])
            node >>= 1
        if self.stats is not None:
            self.stats.k_run_certificate_hits += len(out)
        return out

def _count_causal_onebit_pairs(q: Sequence[int], k: Sequence[int], D: int) -> int:
    """Exact number of causal Q/K center pairs whose symbols differ in exactly one trainable bit."""
    seen: Dict[int, int] = {}
    total = 0
    for u, (qu, ku) in enumerate(zip(q, k)):
        qu = int(qu)
        for j in range(D):
            total += seen.get(qu ^ 1 << j, 0)
        ku = int(ku)
        seen[ku] = seen.get(ku, 0) + 1
    return total

def _build_shared_bridges_sparse(q: Sequence[int], k: Sequence[int], D: int, index: CausalCutSuffixIndex, stats: RepairStats) -> Tuple[List[List[List[_SharedRepairBridge]]], List[List[List[_SharedRepairBridge]]]]:
    """Output-sensitive exact bridge construction: enumerate only one-bit symbol pairs, then 2 LCEs."""
    T = len(q)
    qg = [[[] for _ in range(D)] for _ in range(T)]
    kg = [[[] for _ in range(D)] for _ in range(T)]
    pos: Dict[int, List[int]] = {}
    for p, x in enumerate(k):
        pos.setdefault(int(x), []).append(p)
    for u, qu0 in enumerate(q):
        qu = int(qu0)
        for j in range(D):
            arr = pos.get(qu ^ 1 << j, ())
            z = bisect.bisect_left(arr, u)
            for p0 in arr[:z]:
                p = int(p0)
                L = index.lcs_before_center(u, p)
                R = index.lcp_after_center(u, p)
                b = _SharedRepairBridge(u, p, j, L, R)
                qg[u][j].append(b)
                kg[p][j].append(b)
                stats.shared_bridges += 1
                stats.shared_lce_queries += 2
    return (qg, kg)

def _build_shared_bridges_diagonal(q: Sequence[int], k: Sequence[int], D: int, stats: RepairStats) -> Tuple[List[List[List[_SharedRepairBridge]]], List[List[List[_SharedRepairBridge]]]]:
    """Exact dense bridge construction with no LCE queries.

    For each causal diagonal p=u-h, symbol mismatches partition the diagonal into exact runs.
    A one-bit mismatch center's L/R extents are its distances to the previous/next *symbol*
    mismatch.  Thus every true one-bit repair bridge is obtained in O(1) once the diagonal is
    scanned.
    """
    T = len(q)
    qg = [[[] for _ in range(D)] for _ in range(T)]
    kg = [[[] for _ in range(D)] for _ in range(T)]
    for h in range(1, T):
        start_u = h
        mism: List[Tuple[int, int, Optional[int]]] = []
        for p in range(0, T - h):
            u = p + h
            x = int(q[u]) ^ int(k[p])
            if x:
                mism.append((u, p, _onebit_index(x, D)))
                stats.shared_symbol_mismatches_scanned += 1
        for z, (u, p, j) in enumerate(mism):
            if j is None:
                continue
            prev_u = mism[z - 1][0] if z else start_u - 1
            next_u = mism[z + 1][0] if z + 1 < len(mism) else T
            L = u - prev_u - 1
            R = next_u - u - 1
            b = _SharedRepairBridge(u, p, int(j), int(L), int(R))
            qg[u][j].append(b)
            kg[p][j].append(b)
            stats.shared_bridges += 1
    return (qg, kg)

def _q_shared_terms(qg: Sequence[Sequence[Sequence[_SharedRepairBridge]]], D: int, stats: RepairStats) -> List[List[List[RepairTrackTerm]]]:
    """Exact Q-repair skyline.  All bridges have the same start q_pos for one Q bit."""
    T = len(qg)
    out = [[[] for _ in range(D)] for _ in range(T)]
    for u in range(T):
        for j in range(D):
            bs = qg[u][j]
            if not bs:
                continue
            ordered = sorted(bs, key=lambda b: b.q_priority, reverse=True)
            covered = -1
            for b in ordered:
                if b.right <= covered:
                    continue
                dlo, dhi = (covered + 1, b.right)
                out[u][j].append(RepairTrackTerm(b.shift, u + dlo, u + dhi))
                covered = dhi
                stats.q_shared_skyline_segments += 1
    return out

@dataclass(frozen=True)
class _BridgeInterval:
    lo: int
    hi: int
    priority: Tuple[int, int]
    shift: int

def _first_win_shared_bridge(b: _SharedRepairBridge, owner: int, kdel: KDeleteCutOracle, stats: RepairStats) -> Optional[int]:
    """First t in the bridge lifetime where repair beats the exact post-delete baseline.

    The post-delete normalized route is nonincreasing in t while bridge normalized priority is
    constant, hence the predicate is false* true* and binary-searchable.
    """
    lo, hi = (b.q_pos, b.end_t)
    stats.k_shared_first_win_queries += 1

    def wins(t: int) -> bool:
        stats.k_shared_first_win_probes += 1
        return b.route_at(t) > kdel.route(t, owner)
    if not wins(hi):
        stats.k_shared_first_win_prunes += 1
        return None
    if wins(lo):
        return lo
    a, c = (lo + 1, hi)
    while a < c:
        m = (a + c) // 2
        if wins(m):
            c = m
        else:
            a = m + 1
    return a

def _bridge_envelope_segments(xs: Sequence[_BridgeInterval]):
    """Max constant-priority interval envelope, jumping only at starts/winner expirations."""
    if not xs:
        return
    items = sorted(xs, key=lambda z: (z.lo, z.priority, z.hi))
    n = len(items)
    i = 0
    t = items[0].lo
    heap: List[Tuple[int, int, int, int, _BridgeInterval]] = []
    pending: Optional[Tuple[int, int, _BridgeInterval]] = None

    def flush(seg):
        nonlocal pending
        lo, hi, z = seg
        if pending is not None and pending[2] == z and (pending[1] + 1 == lo):
            pending = (pending[0], hi, z)
            return None
        old = pending
        pending = seg
        return old
    while i < n or heap:
        if not heap and i < n:
            t = max(t, items[i].lo)
        while heap and heap[0][2] < t:
            heapq.heappop(heap)
        while i < n and items[i].lo == t:
            z = items[i]
            a, b = z.priority
            heapq.heappush(heap, (-a, -b, z.hi, i, z))
            i += 1
        while heap and heap[0][2] < t:
            heapq.heappop(heap)
        if not heap:
            if i < n:
                t = items[i].lo
                continue
            break
        win = heap[0][-1]
        next_start = items[i].lo if i < n else 1 << 60
        hi = min(win.hi, next_start - 1)
        old = flush((t, hi, win))
        if old is not None:
            yield old
        t = hi + 1
    if pending is not None:
        yield pending

def _k_shared_terms(kg: Sequence[Sequence[Sequence[_SharedRepairBridge]]], D: int, kdel: KDeleteCutOracle, stats: RepairStats) -> List[List[List[RepairTrackTerm]]]:
    T = len(kg)
    out = [[[] for _ in range(D)] for _ in range(T)]
    for s in range(T):
        for j in range(D):
            clipped: List[_BridgeInterval] = []
            for b in kg[s][j]:
                fw = _first_win_shared_bridge(b, s, kdel, stats)
                if fw is not None:
                    clipped.append(_BridgeInterval(fw, b.end_t, b.k_priority, b.shift))
            for lo, hi, z in _bridge_envelope_segments(clipped):
                out[s][j].append(RepairTrackTerm(z.shift, lo, hi))
                stats.k_shared_envelope_segments += 1
    return out

def _select_repair_backend(T: int, pair_count: int, D: int, max_match_len: int = 1) -> str:
    if pair_count == 0:
        return 'none'
    # If the original route is entirely unmatched, indexed zero-baseline surfaces contract the
    # dense repair triangle without materializing bridges.
    if int(max_match_len) == 0:
        return 'surface_run_certified'

    T = int(T)
    D = int(D)
    lg = math.log2(max(2, T))
    # Long baseline matches are a cheap signal of the repetitive regime where physical bridge
    # materialisation is especially redundant and run-certified surfaces are usually preferable.
    if T >= 96 and int(max_match_len) >= max(32, T // 4):
        return 'surface_run_certified'

    # Shared sparse bridges are excellent when the physical one-bit pair set is genuinely sparse.
    # For D=1 the pair set becomes dense sooner, so use a slightly tighter empirical crossover.
    sparse_factor = 6.0 if D == 1 else 8.0
    sparse_limit = max(1024, int(sparse_factor * max(1, T) * lg))
    if pair_count <= sparse_limit:
        return 'shared_sparse'

    # Dense diagonal materialisation is still fastest for medium random streams.  The run-certified
    # surface compiler wins earlier for low-bit dense streams and for long streams where bridge
    # materialisation is quadratic.  These cutoffs are performance heuristics only; all backends
    # are exact and interchangeable.
    surface_cutoff = 352 if D <= 2 else 448
    if T < surface_cutoff:
        return 'shared_diagonal'
    return 'surface_run_certified'

def _compile_repair_ir(
    q: Sequence[int],
    k: Sequence[int],
    D: int,
    stats: Optional[RepairStats]=None,
    baseline_ell: Optional[Sequence[int]]=None,
    baseline_route: Optional[Sequence[int]]=None,
):
    if stats is None:
        stats = RepairStats()
    index = CausalCutSuffixIndex(q, k)
    if baseline_ell is None and baseline_route is None:
        ell, route = index.matching_stats()
    elif baseline_ell is None or baseline_route is None:
        raise ValueError('baseline_ell and baseline_route must be supplied together')
    else:
        ell = list(map(int, baseline_ell))
        route = list(map(int, baseline_route))
        if len(ell) != len(q) or len(route) != len(q):
            raise ValueError('precomputed baseline certificate length mismatch')
    qheads = _compile_q_latest_heads(index, ell, stats)
    qdel = _build_q_delete_from_latest_heads(ell, qheads, stats)
    kdel = KDeleteCutOracle(index, ell, route, stats)
    pair_count = _count_causal_onebit_pairs(q, k, D)
    stats.onebit_pair_count = int(pair_count)
    backend = _select_repair_backend(len(q), pair_count, D, max(ell, default=0))
    stats.repair_backend = backend
    if backend == 'none':
        qterms = [[[] for _ in range(D)] for _ in range(len(q))]
        kterms = [[[] for _ in range(D)] for _ in range(len(q))]
        zero: List[ZeroBaselineSurface] = []
    elif backend in ('shared_sparse', 'shared_diagonal'):
        if backend == 'shared_sparse':
            qg, kg = _build_shared_bridges_sparse(q, k, D, index, stats)
        else:
            qg, kg = _build_shared_bridges_diagonal(q, k, D, stats)
        if stats.shared_bridges != pair_count:
            raise AssertionError(('shared bridge count mismatch', stats.shared_bridges, pair_count))
        qterms = _q_shared_terms(qg, D, stats)
        kterms = _k_shared_terms(kg, D, kdel, stats)
        zero = []
    elif backend == 'surface_run_certified':
        qterms = _q_repair_terms_suffix_range(q, k, D, index, stats)
        kterms = _compile_k_surface_conditioned(D, index, kdel, ell, stats)
        zero = _zero_baseline_surfaces(q, k, ell, D)
    else:
        raise AssertionError(('unknown repair backend', backend))
    ir = RepairIR(qterms, kterms, qdel, kdel.runs, zero)
    stats.final_surface_terms = sum((len(z) for a in qterms for z in a)) + sum((len(z) for a in kterms for z in a)) + sum((len(x) for x in qdel)) + sum((len(x) for x in kdel.runs)) + len(zero)
    return (ir, ell, route, stats)

def exact_stream_bit_credits(
    q: Sequence[int],
    k: Sequence[int],
    v_bits: torch.Tensor,
    grad_y: torch.Tensor,
    emb0_g: torch.Tensor,
    emb1_g: torch.Tensor,
    n_bits: int,
    baseline_ell: Optional[Sequence[int]]=None,
    baseline_route: Optional[Sequence[int]]=None,
):
    D = int(n_bits)
    stats = RepairStats()
    ir, ell, route, stats = _compile_repair_ir(
        q, k, D, stats, baseline_ell=baseline_ell, baseline_route=baseline_route
    )
    qcred, kcred, vcred = SurfaceVJP.contract(ir, q, k, ell, route, v_bits, grad_y, emb0_g, emb1_g, D, stats)
    return (qcred, kcred, vcred, stats, ell, route, ir)

class _HardQKVRosaFn(torch.autograd.Function):

    @staticmethod
    def forward(ctx, q, k, v, emb0, emb1, n_bits: int, tau: float, credit_to_logit: str):
        B, T, C = q.shape
        D = int(n_bits)
        if k.shape != q.shape or v.shape != q.shape or C % D:
            raise ValueError('invalid q/k/v shape or n_bits')
        G = C // D
        qb = (q > 0).to(torch.uint8).reshape(B, T, G, D)
        kb = (k > 0).to(torch.uint8).reshape(B, T, G, D)
        vb = (v > 0).to(torch.uint8).reshape(B, T, G, D)
        qc, kc = (qb.detach().cpu(), kb.detach().cpu())
        route = torch.full((B, T, G), -1, dtype=torch.long)
        mlen = torch.zeros((B, T, G), dtype=torch.long)
        q_all = [[[] for _ in range(G)] for _ in range(B)]
        k_all = [[[] for _ in range(G)] for _ in range(B)]
        for b in range(B):
            for g in range(G):
                qs = _pack_group_bits_to_python_ints(qc[b, :, g, :])
                ks = _pack_group_bits_to_python_ints(kc[b, :, g, :])
                ell, rr = rosa_qk_matching_stats_static_certificates_symbols(qs, ks)
                q_all[b][g], k_all[b][g] = (qs, ks)
                route[b, :, g] = torch.tensor(rr, dtype=torch.long)
                mlen[b, :, g] = torch.tensor(ell, dtype=torch.long)
        route = route.to(q.device)
        mlen = mlen.to(q.device)
        vidx = (route + 1).clamp_min(0)
        gidx = vidx[..., None].expand(B, T, G, D)
        selected = torch.gather(vb, dim=1, index=gidx)
        matched = route >= 0
        e0 = emb0.expand(B, T, C).reshape(B, T, G, D)
        e1 = emb1.expand(B, T, C).reshape(B, T, G, D)
        sign = selected.to(e1.dtype) * 2.0 - 1.0
        y = torch.where(matched[..., None], sign * e1, e0).reshape(B, T, C)
        ctx.n_bits = D
        ctx.groups = G
        ctx.tau = float(tau)
        ctx.credit_to_logit = str(credit_to_logit)
        ctx.q_all = q_all
        ctx.k_all = k_all
        ctx.save_for_backward(q, k, v, qb, kb, vb, route, mlen, emb0, emb1)
        return y

    @staticmethod
    def backward(ctx, grad_y):
        q, k, v, qb, kb, vb, route, mlen, emb0, emb1 = ctx.saved_tensors
        B, T, C = q.shape
        D, G = (ctx.n_bits, ctx.groups)
        gy4 = grad_y.reshape(B, T, G, D)
        vbc = vb.detach().cpu()
        gyc = gy4.detach().cpu()
        routec = route.detach().cpu()
        mlenc = mlen.detach().cpu()
        e0c = emb0.detach().reshape(G, D).cpu()
        e1c = emb1.detach().reshape(G, D).cpu()
        qfc = torch.zeros((B, T, G, D), dtype=gyc.dtype)
        kfc = torch.zeros_like(qfc)
        vfc = torch.zeros_like(qfc)
        stats_all = []
        for b in range(B):
            row = []
            for g in range(G):
                qa, ka, va, st, _, _, _ = exact_stream_bit_credits(
                    ctx.q_all[b][g],
                    ctx.k_all[b][g],
                    vbc[b, :, g, :],
                    gyc[b, :, g, :],
                    e0c[g],
                    e1c[g],
                    D,
                    baseline_ell=mlenc[b, :, g].tolist(),
                    baseline_route=routec[b, :, g].tolist(),
                )
                qfc[b, :, g, :] = qa
                kfc[b, :, g, :] = ka
                vfc[b, :, g, :] = va
                row.append(st)
            stats_all.append(row)
        ctx.stats_all = stats_all
        qfc = qfc.reshape(B, T, C)
        kfc = kfc.reshape(B, T, C)
        vfc = vfc.reshape(B, T, C)
        grad_q = _flip_credit_to_logit_grad(q, qb.reshape(B, T, C), qfc, ctx.tau, ctx.credit_to_logit)
        grad_k = _flip_credit_to_logit_grad(k, kb.reshape(B, T, C), kfc, ctx.tau, ctx.credit_to_logit)
        grad_v = _flip_credit_to_logit_grad(v, vb.reshape(B, T, C), vfc, ctx.tau, ctx.credit_to_logit)
        matched = (route >= 0).reshape(B, T, G, 1)
        vidx = (route + 1).clamp_min(0)
        gidx = vidx[..., None].expand(B, T, G, D)
        selected = torch.gather(vb, dim=1, index=gidx)
        sign = selected.to(gy4.dtype) * 2.0 - 1.0
        ge0 = torch.where(~matched, gy4, torch.zeros_like(gy4)).sum(dim=(0, 1)).reshape(1, 1, C).to(dtype=emb0.dtype, device=emb0.device)
        ge1 = torch.where(matched, gy4 * sign, torch.zeros_like(gy4)).sum(dim=(0, 1)).reshape(1, 1, C).to(dtype=emb1.dtype, device=emb1.device)
        return (grad_q, grad_k, grad_v, ge0, ge1, None, None, None)

class NBitQKVRosa(nn.Module):
    """Drop-in hard n-bit QKV-ROSA with exact one-bit counterfactual backward."""

    def __init__(self, channels: int, n_bits: int, init_emb1: float=1.0, bias: bool=True, tau: float=1.0, credit_to_logit: str='bernoulli'):
        super().__init__()
        if n_bits <= 0 or channels % n_bits:
            raise ValueError('n_bits must be positive and divide channels')
        self.channels = int(channels)
        self.n_bits = int(n_bits)
        self.groups = channels // n_bits
        self.tau = float(tau)
        self.credit_to_logit = str(credit_to_logit)
        self.q_proj = nn.Linear(channels, channels, bias=bias)
        self.k_proj = nn.Linear(channels, channels, bias=bias)
        self.v_proj = nn.Linear(channels, channels, bias=bias)
        self.o_proj = nn.Linear(channels, channels, bias=bias)
        self.emb0 = nn.Parameter(torch.zeros(1, 1, channels))
        self.emb1 = nn.Parameter(torch.full((1, 1, channels), float(init_emb1)))

    def _hard_rosa_from_qkv(self, q, k, v):
        return _HardQKVRosaFn.apply(q, k, v, self.emb0, self.emb1, self.n_bits, self.tau, self.credit_to_logit)

    def forward(self, x):
        if x.ndim != 3 or x.size(-1) != self.channels:
            raise ValueError('x must have shape [B,T,C]')
        return self.o_proj(self._hard_rosa_from_qkv(self.q_proj(x), self.k_proj(x), self.v_proj(x)))
NBitQKVRosaForward = NBitQKVRosa
