def _merge_affine_runs(xs: Sequence[AffineDeleteRun]) -> List[AffineDeleteRun]:
    out: List[AffineDeleteRun] = []
    for z in sorted(xs, key=lambda a: (a.s_lo, a.s_hi)):
        if z.s_lo > z.s_hi:
            continue
        if out:
            p = out[-1]
            if p.output_t == z.output_t and p.s_hi + 1 == z.s_lo and ((p.len_a, p.len_b, p.end_a, p.end_b) == (z.len_a, z.len_b, z.end_a, z.end_b)):
                out[-1] = AffineDeleteRun(p.output_t, p.s_lo, z.s_hi, p.len_a, p.len_b, p.end_a, p.end_b)
                continue
        out.append(z)
    return out

def _merge_threshold_runs(xs: Sequence[KRepairThresholdRun]) -> List[KRepairThresholdRun]:
    out: List[KRepairThresholdRun] = []
    for z in sorted(xs, key=lambda a: (a.s_lo, a.s_hi)):
        if z.s_lo > z.s_hi:
            continue
        if out:
            p = out[-1]
            if (
                p.output_t == z.output_t
                and p.s_hi + 1 == z.s_lo
                and (p.len_a, p.len_b, p.strict) == (z.len_a, z.len_b, z.strict)
            ):
                out[-1] = KRepairThresholdRun(
                    p.output_t, p.s_lo, z.s_hi, p.len_a, p.len_b, p.strict
                )
                continue
        out.append(z)
    return out

def _compress_singleton_affine(xs: Sequence[AffineDeleteRun]) -> List[AffineDeleteRun]:
    """Merge constant plateaus, then quotient consecutive singleton route records by affine slope."""
    raw = _merge_affine_runs(xs)
    out: List[AffineDeleteRun] = []
    i = 0
    while i < len(raw):
        z = raw[i]
        if z.s_lo != z.s_hi or i + 1 >= len(raw) or raw[i + 1].s_lo != raw[i + 1].s_hi or (raw[i + 1].s_lo != z.s_hi + 1):
            out.append(z)
            i += 1
            continue
        z1 = raw[i + 1]
        s0, s1 = (z.s_lo, z1.s_lo)
        r0, r1 = (z.route(s0), z1.route(s1))
        la, ea = (r1[0] - r0[0], r1[1] - r0[1])
        lb, eb = (r0[0] - la * s0, r0[1] - ea * s0)
        j, last = (i + 2, s1)
        while j < len(raw):
            zj = raw[j]
            if zj.s_lo != zj.s_hi or zj.s_lo != last + 1:
                break
            s = zj.s_lo
            if zj.route(s) != (la * s + lb, ea * s + eb):
                break
            last = s
            j += 1
        out.append(AffineDeleteRun(z.output_t, s0, last, la, lb, ea, eb))
        i = j
    return _merge_affine_runs(out)

class _StaticMaxPByRank:
    """SA-rank segment tree; each leaf contains K reversed position p or -1.

    Supports the nearest SA rank in a rank interval whose K position satisfies p > x.
    This is a static 2D three-sided range-extreme query.
    """

    def __init__(self, values: Sequence[int]):
        n = len(values)
        size = 1
        while size < max(1, n):
            size <<= 1
        self.n, self.size = (n, size)
        self.tr = [-1] * (2 * size)
        for i, v in enumerate(values):
            self.tr[size + i] = int(v)
        for i in range(size - 1, 0, -1):
            self.tr[i] = max(self.tr[i << 1], self.tr[i << 1 | 1])

    def find_last(self, lo: int, hi: int, x: int) -> Optional[int]:
        """Rightmost rank r in [lo,hi) with value[r] > x."""
        lo, hi = (max(0, lo), min(self.n, hi))
        if lo >= hi:
            return None

        def rec(node: int, nl: int, nr: int) -> Optional[int]:
            if nr <= lo or hi <= nl or self.tr[node] <= x:
                return None
            if nr - nl == 1:
                return nl if nl < self.n else None
            m = nl + nr >> 1
            z = rec(node << 1 | 1, m, nr)
            return z if z is not None else rec(node << 1, nl, m)
        return rec(1, 0, self.size)

    def find_first(self, lo: int, hi: int, x: int) -> Optional[int]:
        """Leftmost rank r in [lo,hi) with value[r] > x."""
        lo, hi = (max(0, lo), min(self.n, hi))
        if lo >= hi:
            return None

        def rec(node: int, nl: int, nr: int) -> Optional[int]:
            if nr <= lo or hi <= nl or self.tr[node] <= x:
                return None
            if nr - nl == 1:
                return nl if nl < self.n else None
            m = nl + nr >> 1
            z = rec(node << 1, nl, m)
            return z if z is not None else rec(node << 1 | 1, m, nr)
        return rec(1, 0, self.size)

def _remap_symbols(*seqs: Sequence[Hashable]) -> List[List[int]]:
    """Map arbitrary hashable symbols to positive integers >= 2, consistently across sequences."""
    mp = {}
    nxt = 2
    out: List[List[int]] = []
    for seq in seqs:
        row = []
        for x in seq:
            if x not in mp:
                mp[x] = nxt
                nxt += 1
            row.append(mp[x])
        out.append(row)
    return out

class _StaticRangeSuccessorP:
    """Merge-sort tree over SA rank: minimum K reversed position p > threshold in a rank range.

    A wavelet tree/matrix is the natural production replacement and reduces the logarithmic factors.
    """

    def __init__(self, values: Sequence[int]):
        n = len(values)
        size = 1
        while size < max(1, n):
            size <<= 1
        self.n, self.size = (n, size)
        raw: List[List[int]] = [[] for _ in range(2 * size)]
        for i, v in enumerate(values):
            if int(v) >= 0:
                raw[size + i] = [int(v)]
        for i in range(size - 1, 0, -1):
            a, b = (raw[i << 1], raw[i << 1 | 1])
            row = []
            x = y = 0
            while x < len(a) and y < len(b):
                if a[x] <= b[y]:
                    row.append(a[x])
                    x += 1
                else:
                    row.append(b[y])
                    y += 1
            row.extend(a[x:])
            row.extend(b[y:])
            raw[i] = row
        self.rows = raw

    def range_successor(self, lo: int, hi: int, x: int) -> Optional[int]:
        """Minimum p>x among leaves in rank interval [lo,hi)."""
        lo, hi = (max(0, lo), min(self.n, hi))
        if lo >= hi:
            return None
        lo += self.size
        hi += self.size
        ans = None
        while lo < hi:
            if lo & 1:
                row = self.rows[lo]
                j = bisect.bisect_right(row, int(x))
                if j < len(row) and (ans is None or row[j] < ans):
                    ans = row[j]
                lo += 1
            if hi & 1:
                hi -= 1
                row = self.rows[hi]
                j = bisect.bisect_right(row, int(x))
                if j < len(row) and (ans is None or row[j] < ans):
                    ans = row[j]
            lo >>= 1
            hi >>= 1
        return ans

class _SuffixArrayLCE:
    """Suffix array + Kasai LCP + sparse-table RMQ for O(1) LCE."""

    def __init__(self, seq: Sequence[int]):
        self.seq = list(map(int, seq))
        self.n = len(self.seq)
        self.sa = _suffix_array_int(self.seq)
        self.rank = [0] * self.n
        for r, p in enumerate(self.sa):
            self.rank[p] = r
        lcp = [0] * self.n
        h = 0
        for i in range(self.n):
            r = self.rank[i]
            if r == 0:
                continue
            j = self.sa[r - 1]
            while i + h < self.n and j + h < self.n and (self.seq[i + h] == self.seq[j + h]):
                h += 1
            lcp[r] = h
            if h:
                h -= 1
        self.lcp = lcp
        self.log = [0] * (self.n + 1)
        for i in range(2, self.n + 1):
            self.log[i] = self.log[i >> 1] + 1
        st = [lcp]
        j = 1
        while 1 << j <= self.n:
            prev = st[-1]
            half = 1 << j - 1
            width = 1 << j
            row = [0] * self.n
            lim = self.n - width + 1
            for i in range(max(0, lim)):
                row[i] = min(prev[i], prev[i + half])
            st.append(row)
            j += 1
        self.st = st

    def _rmq_lcp(self, lo: int, hi: int) -> int:
        """min lcp[lo:hi], lo inclusive, hi exclusive; requires lo < hi."""
        length = hi - lo
        j = self.log[length]
        w = 1 << j
        return min(self.st[j][lo], self.st[j][hi - w])

    def lcp_pos(self, a: int, b: int) -> int:
        if a == b:
            return self.n - a
        ra, rb = (self.rank[a], self.rank[b])
        if ra > rb:
            ra, rb = (rb, ra)
        return self._rmq_lcp(ra + 1, rb + 1)

    def prefix_rank_interval(self, pos: int, length: int) -> Tuple[int, int]:
        """Maximal half-open SA-rank interval of suffixes sharing `length` chars with suffix at pos."""
        if length <= 0:
            return (0, self.n)
        r0 = self.rank[pos]
        lo, hi = (0, r0)
        while lo < hi:
            m = (lo + hi) // 2
            if self.lcp_pos(pos, self.sa[m]) >= length:
                hi = m
            else:
                lo = m + 1
        left = lo
        lo, hi = (r0, self.n - 1)
        while lo < hi:
            m = (lo + hi + 1) // 2
            if self.lcp_pos(pos, self.sa[m]) >= length:
                lo = m
            else:
                hi = m - 1
        return (left, lo + 1)

def rosa_qk_matching_stats_static_certificates_symbols(qqq: Sequence[Hashable], kkk: Sequence[Hashable]) -> Tuple[List[int], List[int]]:
    """Same exact ROSA certificates using only static position-restricted suffix-range queries.

    Unlike the sweep version, queries for different output positions t are independent and can be
    batched/parallelized.  Causality is the value constraint p>x in 2D (SA-rank, reversed-position)
    space rather than a dynamically maintained active set.
    """
    n = len(qqq)
    if n != len(kkk):
        raise ValueError('Q/K lengths differ')
    if n == 0:
        return ([], [])
    qi, ki = _remap_symbols(qqq, kkk)
    qr, kr = (list(reversed(qi)), list(reversed(ki)))
    q_off, k_off = (0, n + 1)
    text = qr + [0] + kr + [1]
    idx = _SuffixArrayLCE(text)
    rank_to_p = [-1] * len(text)
    for p in range(n):
        rank_to_p[idx.rank[k_off + p]] = p
    extrema = _StaticMaxPByRank(rank_to_p)
    succ_p = _StaticRangeSuccessorP(rank_to_p)
    lens = [0] * n
    route_end = [-1] * n
    N = len(text)
    for t in range(n):
        x = n - 1 - t
        qpos = q_off + x
        rq = idx.rank[qpos]
        rp = extrema.find_last(0, rq, x)
        rs = extrema.find_first(rq + 1, N, x)
        best = 0
        if rp is not None:
            best = max(best, idx.lcp_pos(qpos, idx.sa[rp]))
        if rs is not None:
            best = max(best, idx.lcp_pos(qpos, idx.sa[rs]))
        if best <= 0:
            continue
        lo, hi = idx.prefix_rank_interval(qpos, best)
        p_star = succ_p.range_successor(lo, hi, x)
        if p_star is None:
            raise AssertionError('static position-restricted winner interval lost K suffix')
        e_star = n - 1 - p_star
        best = min(best, t + 1, e_star + 1)
        if best > 0:
            lens[t] = int(best)
            route_end[t] = int(e_star)
    return (lens, route_end)

