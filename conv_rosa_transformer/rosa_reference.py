@dataclass(frozen=True)
class ZeroBaselineSurface:
    """Exact K repair surface for outputs whose delete baseline is unmatched.

    A K owner s with symbol k_symbol and bit j can be changed to target_symbol.  For every output t
    with Q[t]==target_symbol, match_len[t]==0 and s<t, the repaired winner ends at s and therefore
    selects payload V[s+1].  The entire triangular owner-output family is contracted without
    materializing its pairs.
    """
    bit: int
    k_symbol: int
    target_symbol: int
Route = Tuple[int, int]

@dataclass(frozen=True)
class AffineDeleteRun:
    """Exact owner-axis route family: L(s)=len_a*s+len_b, r(s)=end_a*s+end_b."""
    output_t: int
    s_lo: int
    s_hi: int
    len_a: int
    len_b: int
    end_a: int
    end_b: int

    def route(self, s: int) -> Route:
        if not self.s_lo <= s <= self.s_hi:
            raise ValueError('owner outside AffineDeleteRun')
        return (self.len_a * int(s) + self.len_b, self.end_a * int(s) + self.end_b)

@dataclass(frozen=True)
class KRepairThresholdRun:
    """Owner-axis repair threshold q(s).

    If strict is False, every repaired route with length >= L(s) beats the delete context.
    If strict is True, it must have length > L(s).  Since a real repair has length >= 1,
    threshold_length() returns the single fixed-pattern length that is necessary and sufficient.
    """
    output_t: int
    s_lo: int
    s_hi: int
    len_a: int
    len_b: int
    strict: bool

    def baseline_length(self, s: int) -> int:
        if not self.s_lo <= s <= self.s_hi:
            raise ValueError('owner outside KRepairThresholdRun')
        return self.len_a * int(s) + self.len_b

    def threshold_length(self, s: int) -> int:
        return max(1, self.baseline_length(s) + (1 if self.strict else 0))

