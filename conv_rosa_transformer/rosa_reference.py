class _RangePositionIndex:
    """Merge-sort tree keyed by SA rank, values are text positions.

    Supports range min/max and output-sensitive reporting in rank interval x position interval.
    This is the reference stand-in for a wavelet matrix.
    """

    def __init__(self, values: Sequence[Optional[int]]):
        self.n = len(values)
        size = 1
        while size < max(1, self.n):
            size <<= 1
        self.size = size
        raw: List[List[int]] = [[] for _ in range(2 * size)]
        for i, v in enumerate(values):
            if v is not None:
                raw[size + i] = [int(v)]
        for i in range(size - 1, 0, -1):
            a, b = (raw[i << 1], raw[i << 1 | 1])
            x = []
            p = q = 0
            while p < len(a) and q < len(b):
                if a[p] <= b[q]:
                    x.append(a[p])
                    p += 1
                else:
                    x.append(b[q])
                    q += 1
            x.extend(a[p:])
            x.extend(b[q:])
            raw[i] = x
        self.rows = raw

    def _nodes(self, lo: int, hi: int) -> List[int]:
        lo, hi = (max(0, int(lo)), min(self.n, int(hi)))
        if lo >= hi:
            return []
        lo += self.size
        hi += self.size
        out = []
        while lo < hi:
            if lo & 1:
                out.append(lo)
                lo += 1
            if hi & 1:
                hi -= 1
                out.append(hi)
            lo >>= 1
            hi >>= 1
        return out

    def min_in(self, lo: int, hi: int, p_lo: int, p_hi: int) -> Optional[int]:
        """Minimum p with p_lo <= p <= p_hi in rank interval."""
        ans = None
        for node in self._nodes(lo, hi):
            row = self.rows[node]
            j = bisect.bisect_left(row, int(p_lo))
            if j < len(row) and row[j] <= int(p_hi):
                z = row[j]
                if ans is None or z < ans:
                    ans = z
        return ans

    def max_in(self, lo: int, hi: int, p_lo: int, p_hi: int) -> Optional[int]:
        ans = None
        for node in self._nodes(lo, hi):
            row = self.rows[node]
            j = bisect.bisect_right(row, int(p_hi)) - 1
            if j >= 0 and row[j] >= int(p_lo):
                z = row[j]
                if ans is None or z > ans:
                    ans = z
        return ans

    def report(self, lo: int, hi: int, p_lo: int, p_hi: int) -> List[int]:
        """Report positions in rank rectangle, output-sensitive up to O(log n) node duplication.

        Canonical SA leaves are disjoint across `_nodes`, so every position appears exactly once.
        """
        out: List[int] = []
        for node in self._nodes(lo, hi):
            row = self.rows[node]
            a = bisect.bisect_left(row, int(p_lo))
            b = bisect.bisect_right(row, int(p_hi))
            out.extend(row[a:b])
        return out

class _MinPRange:
    """Range minimum over p plus exact first/last index whose p<threshold."""

    def __init__(self, values: Sequence[int]):
        self.n = len(values)
        size = 1
        while size < max(1, self.n):
            size <<= 1
        self.size = size
        inf = 1 << 60
        tr = [inf] * (2 * size)
        for i, x in enumerate(values):
            tr[size + i] = int(x)
        for i in range(size - 1, 0, -1):
            tr[i] = min(tr[2 * i], tr[2 * i + 1])
        self.tr = tr

    def find_last(self, right_exclusive: int, threshold: int) -> Optional[int]:
        ql, qr = (0, min(self.n, int(right_exclusive)))
        if ql >= qr:
            return None

        def rec(node, nl, nr):
            if nr <= ql or qr <= nl or self.tr[node] >= threshold:
                return None
            if nr - nl == 1:
                return nl if nl < self.n else None
            mid = (nl + nr) // 2
            z = rec(node * 2 + 1, mid, nr)
            return z if z is not None else rec(node * 2, nl, mid)
        return rec(1, 0, self.size)

    def find_first(self, left: int, threshold: int) -> Optional[int]:
        ql, qr = (max(0, int(left)), self.n)
        if ql >= qr:
            return None

        def rec(node, nl, nr):
            if nr <= ql or qr <= nl or self.tr[node] >= threshold:
                return None
            if nr - nl == 1:
                return nl if nl < self.n else None
            mid = (nl + nr) // 2
            z = rec(node * 2, nl, mid)
            return z if z is not None else rec(node * 2 + 1, mid, nr)
        return rec(1, 0, self.size)

class _MergeRangePredecessor:
    """Segment tree of sorted integer values; predecessor in index interval."""

    def __init__(self, values_by_index: Sequence[Optional[int]]):
        n = len(values_by_index)
        size = 1
        while size < max(1, n):
            size <<= 1
        self.size = size
        tree: List[List[int]] = [[] for _ in range(2 * size)]
        for i, x in enumerate(values_by_index):
            if x is not None:
                tree[size + i] = [int(x)]
        for i in range(size - 1, 0, -1):
            a, b = (tree[2 * i], tree[2 * i + 1])
            out: List[int] = []
            p = q = 0
            while p < len(a) and q < len(b):
                if a[p] <= b[q]:
                    out.append(a[p])
                    p += 1
                else:
                    out.append(b[q])
                    q += 1
            out.extend(a[p:])
            out.extend(b[q:])
            tree[i] = out
        self.tree = tree

    def predecessor(self, left: int, right: int, x: int) -> Optional[int]:
        if left >= right:
            return None
        left += self.size
        right += self.size
        ans: Optional[int] = None
        while left < right:
            if left & 1:
                arr = self.tree[left]
                z = bisect.bisect_right(arr, x) - 1
                if z >= 0 and (ans is None or arr[z] > ans):
                    ans = arr[z]
                left += 1
            if right & 1:
                right -= 1
                arr = self.tree[right]
                z = bisect.bisect_right(arr, x) - 1
                if z >= 0 and (ans is None or arr[z] > ans):
                    ans = arr[z]
            left >>= 1
            right >>= 1
        return ans

class _YBucket:
    """Points sorted by reverse-SA rank y inside one outer forward-rank node."""

    def __init__(self, points: Sequence[Tuple[int, int]]):
        xs = sorted(((int(y), int(p)) for y, p in points))
        self.ys = [a for a, _ in xs]
        self.ps = [b for _, b in xs]
        self.minp = _MinPRange(self.ps)
        self.predp = _MergeRangePredecessor(self.ps)

    def pred_y(self, yq: int, owner_u: int) -> Optional[Tuple[int, int]]:
        idx = bisect.bisect_right(self.ys, int(yq))
        z = self.minp.find_last(idx, int(owner_u))
        return None if z is None else (self.ys[z], self.ps[z])

    def succ_y(self, yq: int, owner_u: int) -> Optional[Tuple[int, int]]:
        idx = bisect.bisect_left(self.ys, int(yq))
        z = self.minp.find_first(idx, int(owner_u))
        return None if z is None else (self.ys[z], self.ps[z])

    def max_p(self, ylo: int, yhi: int, owner_u: int) -> Optional[int]:
        a = bisect.bisect_left(self.ys, int(ylo))
        b = bisect.bisect_left(self.ys, int(yhi))
        return self.predp.predecessor(a, b, int(owner_u) - 1)

class _SymbolOrthogonalOracle:
    """Exact rectangle oracle over one target symbol's center points.

    Outer axis: forward-SA rank of K[p+1:].
    Inner axis: reverse-SA rank of K[:p] reversed.
    Payload/causality coordinate: p.  Query supports nearest reverse rank and latest p<u in a
    reverse-rank interval, on a forward-rank slice.  Construction is O(m log m) buckets for m
    occurrences of this symbol; queries are polylogarithmic in m in the reference implementation.
    """

    def __init__(self, points: Sequence[Tuple[int, int, int]]):
        pts = sorted(((int(x), int(y), int(p)) for x, y, p in points))
        self.xs = [x for x, _, _ in pts]
        self.n = len(pts)
        size = 1
        while size < max(1, self.n):
            size <<= 1
        self.size = size
        buckets: List[Optional[_YBucket]] = [None] * (2 * size)
        leaves = [[] for _ in range(size)]
        for i, (_, y, p) in enumerate(pts):
            leaves[i] = [(y, p)]
        raw = [[] for _ in range(2 * size)]
        for i in range(size):
            raw[size + i] = leaves[i]
        for i in range(size - 1, 0, -1):
            raw[i] = raw[2 * i] + raw[2 * i + 1]
        for i in range(1, 2 * size):
            if raw[i]:
                buckets[i] = _YBucket(raw[i])
        self.buckets = buckets

    def _nodes(self, xlo: int, xhi: int):
        l = bisect.bisect_left(self.xs, int(xlo))
        r = bisect.bisect_left(self.xs, int(xhi))
        l += self.size
        r += self.size
        out = []
        while l < r:
            if l & 1:
                out.append(l)
                l += 1
            if r & 1:
                r -= 1
                out.append(r)
            l >>= 1
            r >>= 1
        return out

    def nearest(self, xlo: int, xhi: int, yq: int, owner_u: int):
        pred = None
        succ = None
        for node in self._nodes(xlo, xhi):
            b = self.buckets[node]
            if b is None:
                continue
            z = b.pred_y(yq, owner_u)
            if z is not None and (pred is None or z[0] > pred[0]):
                pred = z
            z = b.succ_y(yq, owner_u)
            if z is not None and (succ is None or z[0] < succ[0]):
                succ = z
        return (pred, succ)

    def max_p(self, xlo: int, xhi: int, ylo: int, yhi: int, owner_u: int) -> Optional[int]:
        ans = None
        for node in self._nodes(xlo, xhi):
            b = self.buckets[node]
            if b is None:
                continue
            z = b.max_p(ylo, yhi, owner_u)
            if z is not None and (ans is None or z > ans):
                ans = z
        return ans

class BiPositionSuffixIndex:
    """Universal structural index over Q/K and their reversals."""

    def __init__(self, q: Sequence[int], k: Sequence[int]):
        if len(q) != len(k):
            raise ValueError('Q/K lengths differ')
        self.T = len(q)
        self.q = list(map(int, q))
        self.k = list(map(int, k))
        qi, ki = _remap_symbols(self.q, self.k)
        T = self.T
        self.q_off = 0
        self.k_off = T + 1
        self.fwd = _SuffixArrayLCE(qi + [0] + ki + [1])
        qr = list(reversed(qi))
        kr = list(reversed(ki))
        self.rq_off = 0
        self.rk_off = T + 1
        self.rev = _SuffixArrayLCE(qr + [0] + kr + [1])
        fvals: List[Optional[int]] = [None] * self.fwd.n
        for a in range(T):
            fvals[self.fwd.rank[self.k_off + a]] = a
        self.fpos = _RangePositionIndex(fvals)
        rvals: List[Optional[int]] = [None] * self.rev.n
        for p in range(T):
            rvals[self.rev.rank[self.rk_off + p]] = p
        self.rpos = _RangePositionIndex(rvals)
        self.positions_by_symbol: Dict[int, List[int]] = {}
        for a, x in enumerate(self.k):
            self.positions_by_symbol.setdefault(int(x), []).append(a)
        self._onebit_cache: Dict[Tuple[int, int, int, int, int], List[_OneBitOccurrence]] = {}
        self._q_orth: Dict[int, _SymbolOrthogonalOracle] = {}

    def lcp_after_center(self, u: int, p: int) -> int:
        if u + 1 >= self.T or p + 1 >= self.T:
            return 0
        return min(self.fwd.lcp_pos(self.q_off + u + 1, self.k_off + p + 1), self.T - u - 1, self.T - p - 1)

    def lcs_before_center(self, u: int, p: int) -> int:
        if u <= 0 or p <= 0:
            return 0
        return min(self.rev.lcp_pos(self.rq_off + self.T - u, self.rk_off + self.T - p), u, p)

    def q_pattern_interval(self, t: int, L: int) -> Tuple[int, int]:
        if L <= 0:
            return (0, self.fwd.n)
        return self.fwd.prefix_rank_interval(self.q_off + t - L + 1, L)

    def q_reversed_prefix_interval(self, t: int, L: int) -> Tuple[int, int]:
        if L <= 0:
            return (0, self.rev.n)
        x = self.T - 1 - t
        return self.rev.prefix_rank_interval(self.rq_off + x, L)

    def _q_orth_for_symbol(self, target: int) -> _SymbolOrthogonalOracle:
        target = int(target)
        z = self._q_orth.get(target)
        if z is not None:
            return z
        pts = []
        for p, sym in enumerate(self.k):
            if int(sym) != target:
                continue
            xrank = self.fwd.rank[self.k_off + p + 1]
            yrank = self.rev.rank[self.rk_off + (self.T - p)]
            pts.append((xrank, yrank, p))
        z = _SymbolOrthogonalOracle(pts)
        self._q_orth[target] = z
        return z

    def direct_q_best_center(self, target: int, u: int, depth: int) -> Optional[Tuple[int, int]]:
        orth = self._q_orth_for_symbol(target)
        if orth.n == 0:
            return None
        if depth <= 0 or u + 1 >= self.T:
            xl, xr = (0, self.fwd.n)
        else:
            xl, xr = self.fwd.prefix_rank_interval(self.q_off + u + 1, depth)
        qrev_pos = self.rq_off + (self.T - u)
        yq = self.rev.rank[qrev_pos]
        pred, succ = orth.nearest(xl, xr, yq, u)
        cands = []
        for z in (pred, succ):
            if z is not None:
                _, p = z
                cands.append((self.lcs_before_center(u, p), p))
        if not cands:
            return None
        Lstar = max((a for a, _ in cands))
        if Lstar <= 0:
            ylo, yhi = (0, self.rev.n)
        else:
            ylo, yhi = self.rev.prefix_rank_interval(qrev_pos, Lstar)
        pbest = orth.max_p(xl, xr, ylo, yhi, u)
        if pbest is None:
            raise AssertionError(('direct Q tie query lost candidate', target, u, depth, Lstar))
        Lbest = self.lcs_before_center(u, pbest)
        if Lbest != Lstar:
            raise AssertionError(('direct Q max-L mismatch', target, u, depth, Lstar, pbest, Lbest))
        return (int(pbest), int(Lbest))

    def matching_stats(self) -> Tuple[List[int], List[int]]:
        return rosa_qk_matching_stats_static_certificates_symbols(self.q, self.k)

    def _report_q_substring_starts(self, q_start: int, length: int, k_start_lo: int, k_start_hi: int) -> List[int]:
        if length <= 0:
            if k_start_lo > k_start_hi:
                return []
            return list(range(max(0, k_start_lo), min(self.T - 1, k_start_hi) + 1))
        if q_start < 0 or q_start + length > self.T:
            return []
        l, r = self.fwd.prefix_rank_interval(self.q_off + q_start, length)
        return self.fpos.report(l, r, max(0, k_start_lo), min(self.T - 1, k_start_hi))

    def one_bit_occurrences_filtered(self, t: int, L: int, S0: int, S1: int, D: int, stats: Optional[RepairStats]=None) -> List[_OneBitOccurrence]:
        """Exact one-bit occurrences with mismatch owner constrained to [S0,S1] before reporting.

        Two-seed candidate generation is position-restricted at the range-query layer.  Verification
        remains exact via two LCE jumps and an exact power-of-two xor check.
        """
        t = int(t)
        L = int(L)
        S0 = max(0, int(S0))
        S1 = min(t - 1, int(S1))
        D = int(D)
        if L <= 0 or L > t + 1 or S0 > S1:
            return []
        key = (t, L, S0, S1, D)
        zc = self._onebit_cache.get(key)
        if zc is not None:
            return zc
        q0 = t - L + 1
        starts = set()
        if L == 1:
            qsym = int(self.q[t])
            for bit in range(D):
                target = qsym ^ 1 << bit
                arr = self.positions_by_symbol.get(target, ())
                a = bisect.bisect_left(arr, S0)
                b = bisect.bisect_right(arr, S1)
                for s in arr[a:b]:
                    if s < t:
                        starts.add(int(s))
        else:
            h = L // 2
            lo = max(0, S0 - L + 1)
            hi = min(S1 - h, t - L, self.T - L)
            if h > 0 and lo <= hi:
                for a in self._report_q_substring_starts(q0, h, lo, hi):
                    starts.add(int(a))
            tail = L - h
            alo = max(0, S0 - h + 1)
            ahi = min(S1, t - L, self.T - L)
            if tail > 0 and alo <= ahi:
                blo, bhi = (alo + h, ahi + h)
                for b0 in self._report_q_substring_starts(q0 + h, tail, blo, bhi):
                    starts.add(int(b0) - h)
        if stats is not None:
            stats.k_onebit_seed_reports += len(starts)
        out = []
        for a in starts:
            if not (0 <= a and a + L - 1 < t):
                continue
            x = min(L, self.fwd.lcp_pos(self.q_off + q0, self.k_off + a))
            if x >= L:
                continue
            s = a + x
            if not S0 <= s <= S1:
                if stats is not None:
                    stats.k_owner_range_prunes += 1
                continue
            xo = int(self.q[q0 + x]) ^ int(self.k[s])
            if xo <= 0 or xo & xo - 1 or xo.bit_length() - 1 >= D:
                continue
            rem = L - x - 1
            y = 0 if rem <= 0 else min(rem, self.fwd.lcp_pos(self.q_off + q0 + x + 1, self.k_off + a + x + 1))
            if y != rem:
                continue
            out.append(_OneBitOccurrence(a, a + L - 1, s, xo.bit_length() - 1))
        if stats is not None:
            stats.k_onebit_verified += len(out)
        uniq = {(o.start, o.end, o.mismatch_owner, o.bit): o for o in out}
        z = list(uniq.values())
        z.sort(key=lambda o: (o.start, o.end, o.mismatch_owner, o.bit))
        self._onebit_cache[key] = z
        return z
class CausalCutSuffixIndex(BiPositionSuffixIndex):
    """Suffix index plus direct most-recent/cut-envelope and repair primitives."""

    def lcs_end(self, t: int, e: int) -> int:
        if t < 0 or e < 0:
            return 0
        x = self.T - 1 - int(t)
        p = self.T - 1 - int(e)
        return min(self.rev.lcp_pos(self.rq_off + x, self.rk_off + p), int(t) + 1, int(e) + 1)

    def latest_endpoint_for_suffix(self, t: int, L: int) -> Optional[int]:
        """Latest causal endpoint of Q[t-L+1:t], or None."""
        t, L = (int(t), int(L))
        if L <= 0 or L > t + 1:
            return None
        l, r = self.q_pattern_interval(t, L)
        a = self.fpos.max_in(l, r, 0, t - L)
        return None if a is None else int(a + L - 1)

    def next_endpoint_at_least(self, t: int, L: int, after_e: int) -> Optional[int]:
        """Smallest endpoint e>after_e with LCSuffix(Q[:t+1],K[:e+1]) >= L."""
        t, L, after_e = (int(t), int(L), int(after_e))
        if L <= 0 or L > t + 1:
            return None
        l, r = self.q_pattern_interval(t, L)
        lo = max(0, after_e - L + 2)
        hi = t - L
        if lo > hi:
            return None
        a = self.fpos.min_in(l, r, lo, hi)
        return None if a is None else int(a + L - 1)

    def F_reversed(self, t: int, p: int) -> int:
        """F_t(p)=LCP(QR[x:],KR[p:]), semantically clamped."""
        t, p = (int(t), int(p))
        x = self.T - 1 - t
        if not x < p < self.T:
            return 0
        e = self.T - 1 - p
        return min(self.rev.lcp_pos(self.rq_off + x, self.rk_off + p), t + 1, e + 1)

    def min_p_with_F_at_least(self, t: int, L: int, p_lo: int, p_hi: Optional[int]=None) -> Optional[int]:
        t, L, p_lo = (int(t), int(L), int(p_lo))
        if p_hi is None:
            p_hi = self.T - 1
        p_hi = int(p_hi)
        if L <= 0:
            return p_lo if p_lo <= p_hi else None
        if p_lo > p_hi or L > t + 1:
            return None
        l, r = self.q_reversed_prefix_interval(t, L)
        return self.rpos.min_in(l, r, p_lo, p_hi)

class MostRecentSuffixMatchOracle:
    """A_t(s): best route whose historical K endpoint e is strictly smaller than owner s.

    The profile is generated by A-jumps.  If current route has length L and endpoint e, it remains
    unchanged until the next endpoint u>e containing the same length-L query suffix.  At u+1 the
    route becomes (LCSuffix(t,u),u).  Equal-length occurrences are records because ROSA prefers the
    latest endpoint.  The resulting record surfaces are affine-quotiented after generation.
    """

    def __init__(self, index: CausalCutSuffixIndex, stats: Optional[RepairStats]=None):
        self.index = index
        self.stats = stats
        self._cache: Dict[int, List[AffineDeleteRun]] = {}
        self._starts: Dict[int, List[int]] = {}

    def compile(self, t: int) -> List[AffineDeleteRun]:
        t = int(t)
        if t in self._cache:
            return self._cache[t]
        if t <= 0:
            self._cache[t] = []
            self._starts[t] = []
            return []
        raw: List[AffineDeleteRun] = []
        u = self.index.next_endpoint_at_least(t, 1, -1)
        if u is None:
            raw = [AffineDeleteRun(t, 0, t - 1, 0, 0, 0, -1)]
        else:
            raw.append(AffineDeleteRun(t, 0, min(u, t - 1), 0, 0, 0, -1))
            cur_e, cur_L, cur_s = (int(u), self.index.lcs_end(t, u), int(u) + 1)
            while cur_s <= t - 1:
                if self.stats is not None:
                    self.stats.a_jump_records += 1
                nxt = self.index.next_endpoint_at_least(t, cur_L, cur_e)
                hi = t - 1 if nxt is None else min(int(nxt), t - 1)
                raw.append(AffineDeleteRun(t, cur_s, hi, 0, cur_L, 0, cur_e))
                if nxt is None or int(nxt) + 1 > t - 1:
                    break
                cur_e = int(nxt)
                cur_L = self.index.lcs_end(t, cur_e)
                cur_s = cur_e + 1
        if self.stats is not None:
            self.stats.a_raw_runs += len(raw)
            self.stats.a_pair_equiv += t
        out = _compress_singleton_affine(raw)
        if self.stats is not None:
            self.stats.a_affine_runs += len(out)
        self._cache[t] = out
        self._starts[t] = [z.s_lo for z in out]
        return out

    def route(self, t: int, s: int) -> Route:
        xs = self.compile(t)
        if not xs:
            return (0, -1)
        starts = self._starts[int(t)]
        i = bisect.bisect_right(starts, int(s)) - 1
        if i >= 0 and xs[i].s_lo <= s <= xs[i].s_hi:
            return xs[i].route(s)
        return (0, -1)

class TruncatedRightMatchOracle:
    """H_t(s): best occurrence lying wholly to the right of K owner s.

    In reversed coordinates b=T-1-s and p is a reversed K suffix start.  Each p contributes
        h_p(b)=min(F_t(p), b-p), p<=b,
    a ramp followed by a plateau.  A ramp winner is unbeatable until saturation.  Once saturated
    at height F, the next possible winner is the smallest q>p with F_t(q)>=F+1, and it first wins
    at b=q+F+1.  This gives an exact jump compiler with no owner scan.
    """

    def __init__(self, index: CausalCutSuffixIndex, stats: Optional[RepairStats]=None):
        self.index = index
        self.stats = stats
        self._cache: Dict[int, List[AffineDeleteRun]] = {}

    def compile(self, t: int) -> List[AffineDeleteRun]:
        t = int(t)
        if t in self._cache:
            return self._cache[t]
        if t <= 0:
            self._cache[t] = []
            return []
        T = self.index.T
        x = T - 1 - t
        bouts: List[Tuple[int, int, str, int, int]] = []
        p = self.index.min_p_with_F_at_least(t, 1, x + 1, T - 1)
        if p is None or p + 1 > T - 1:
            out = [AffineDeleteRun(t, 0, t - 1, 0, 0, 0, -1)]
            self._cache[t] = out
            if self.stats is not None:
                self.stats.h_pair_equiv += t
            return out
        if x + 1 <= p:
            bouts.append((x + 1, int(p), 'unmatched', 0, -1))
        bcur = int(p) + 1
        while bcur <= T - 1:
            F = self.index.F_reversed(t, int(p))
            if F <= 0:
                raise AssertionError(('H winner with zero F', t, p, bcur))
            sat = min(T - 1, int(p) + F)
            if bcur <= sat:
                e = T - 1 - int(p)
                bouts.append((bcur, sat, 'ramp', 0, e))
                if self.stats is not None:
                    self.stats.h_ramp_runs += 1
            if sat >= T - 1:
                break
            q = self.index.min_p_with_F_at_least(t, F + 1, int(p) + 1, T - 1)
            e = T - 1 - int(p)
            if q is None:
                if sat + 1 <= T - 1:
                    bouts.append((sat + 1, T - 1, 'plateau', F, e))
                    if self.stats is not None:
                        self.stats.h_plateau_runs += 1
                break
            bnext = int(q) + F + 1
            if sat + 1 <= min(T - 1, bnext - 1):
                bouts.append((sat + 1, min(T - 1, bnext - 1), 'plateau', F, e))
                if self.stats is not None:
                    self.stats.h_plateau_runs += 1
            if bnext > T - 1:
                break
            p = int(q)
            bcur = bnext
        out: List[AffineDeleteRun] = []
        for blo, bhi, kind, param, e in bouts:
            slo = max(0, T - 1 - bhi)
            shi = min(t - 1, T - 1 - blo)
            if slo > shi:
                continue
            if kind == 'unmatched':
                out.append(AffineDeleteRun(t, slo, shi, 0, 0, 0, -1))
            elif kind == 'ramp':
                out.append(AffineDeleteRun(t, slo, shi, -1, e, 0, e))
            else:
                out.append(AffineDeleteRun(t, slo, shi, 0, param, 0, e))
        out = _merge_affine_runs(out)
        cur = 0
        for z in out:
            if z.s_lo != cur:
                raise AssertionError(('H coverage gap', t, cur, z, out))
            cur = z.s_hi + 1
        if cur != t:
            raise AssertionError(('H coverage tail', t, cur, out))
        if self.stats is not None:
            self.stats.h_pair_equiv += t
        self._cache[t] = out
        return out

def _clip_run(z: AffineDeleteRun, lo: int, hi: int) -> Optional[AffineDeleteRun]:
    a = max(int(lo), z.s_lo)
    b = min(int(hi), z.s_hi)
    return None if a > b else AffineDeleteRun(z.output_t, a, b, z.len_a, z.len_b, z.end_a, z.end_b)

def _merge_A_H_surface_runs(
    a_runs: Sequence[AffineDeleteRun],
    h_runs: Sequence[AffineDeleteRun],
    t: int,
    s_lo: int,
    s_hi: int,
    stats: Optional[RepairStats]=None,
) -> Tuple[List[AffineDeleteRun], List[KRepairThresholdRun]]:
    """Exact max(A,H), retaining the repair threshold polarity of the winning context.

    A winners end strictly before the edited owner, so an equal-length repair wins the endpoint tie
    (inclusive threshold). H winners lie wholly to the right of the owner, so every equal-length
    repair crossing the owner loses the endpoint tie (strict threshold).
    """
    A = [z for x in a_runs if (z := _clip_run(x, s_lo, s_hi)) is not None]
    H = [z for x in h_runs if (z := _clip_run(x, s_lo, s_hi)) is not None]
    routes: List[AffineDeleteRun] = []
    reqs: List[KRepairThresholdRun] = []

    def emit(z: AffineDeleteRun, lo: int, hi: int, strict: bool) -> None:
        routes.append(AffineDeleteRun(t, lo, hi, z.len_a, z.len_b, z.end_a, z.end_b))
        reqs.append(KRepairThresholdRun(t, lo, hi, z.len_a, z.len_b, strict))

    i = j = 0
    while i < len(A) and j < len(H):
        za, zh = A[i], H[j]
        lo = max(za.s_lo, zh.s_lo)
        hi = min(za.s_hi, zh.s_hi)
        if lo <= hi:
            if za.route(lo) > zh.route(lo):
                emit(za, lo, hi, False)
            elif za.route(hi) <= zh.route(hi):
                emit(zh, lo, hi, True)
            else:
                l, r = lo, hi
                while l < r:
                    m = (l + r) // 2
                    if za.route(m) > zh.route(m):
                        r = m
                    else:
                        l = m + 1
                c = l
                if lo <= c - 1:
                    emit(zh, lo, c - 1, True)
                emit(za, c, hi, False)
                if stats is not None:
                    stats.ah_crossings += 1
        ae, he = za.s_hi, zh.s_hi
        if ae <= he:
            i += 1
        if he <= ae:
            j += 1

    routes = _merge_affine_runs(routes)
    reqs = _merge_threshold_runs(reqs)
    for xs, label in ((routes, 'route'), (reqs, 'threshold')):
        cur = s_lo
        for z in xs:
            if z.s_lo != cur:
                raise AssertionError(('A/H gap', label, t, s_lo, s_hi, cur, z, xs))
            cur = z.s_hi + 1
        if cur != s_hi + 1:
            raise AssertionError(('A/H tail', label, t, s_lo, s_hi, cur, xs))
    return routes, reqs

class KDeleteCutOracle:
    """Exact K-delete baseline plus its minimal one-mismatch repair requirement surfaces."""

    def __init__(
        self,
        index: CausalCutSuffixIndex,
        ell: Sequence[int],
        route: Sequence[int],
        stats: Optional[RepairStats]=None,
    ):
        self.index = index
        self.ell = list(map(int, ell))
        self.route0 = list(map(int, route))
        self.stats = stats
        self.A = MostRecentSuffixMatchOracle(index, stats)
        self.H = TruncatedRightMatchOracle(index, stats)
        self.runs: List[List[AffineDeleteRun]] = [[] for _ in self.ell]
        self.starts: List[List[int]] = [[] for _ in self.ell]
        self.repair_runs: List[List[KRepairThresholdRun]] = [[] for _ in self.ell]

        for t, (L0, r0) in enumerate(zip(self.ell, self.route0)):
            if L0 <= 0 or r0 < 0:
                continue
            wlo, whi = r0 - L0 + 1, r0
            routes, req_inside = _merge_A_H_surface_runs(
                self.A.compile(t), self.H.compile(t), t, wlo, whi, stats
            )
            self.runs[t] = routes
            self.starts[t] = [z.s_lo for z in routes]

            # Outside the original matched K interval, deleting owner s leaves the baseline route
            # unchanged. If s lies left of that interval, every equal-length repaired occurrence
            # crossing s ends before r0 and loses the tie: strict. If s lies right of r0, every
            # equal-length repaired occurrence ends after r0 and wins the tie: inclusive.
            req_full: List[KRepairThresholdRun] = []
            if wlo > 0:
                req_full.append(KRepairThresholdRun(t, 0, wlo - 1, 0, L0, True))
            req_full.extend(req_inside)
            if whi + 1 <= t - 1:
                req_full.append(KRepairThresholdRun(t, whi + 1, t - 1, 0, L0, False))
            self.repair_runs[t] = _merge_threshold_runs(req_full)

            cur = 0
            for z in self.repair_runs[t]:
                if z.s_lo != cur:
                    raise AssertionError(('K repair threshold gap', t, cur, z, self.repair_runs[t]))
                cur = z.s_hi + 1
            if cur != t:
                raise AssertionError(('K repair threshold tail', t, cur, self.repair_runs[t]))

            if stats is not None:
                stats.k_delete_runs += len(routes)
                stats.k_delete_pair_equiv += L0
                stats.k_surface_regions += len(self.repair_runs[t])

    def route(self, t: int, s: int) -> Route:
        xs = self.runs[int(t)]
        i = bisect.bisect_right(self.starts[int(t)], int(s)) - 1
        if i >= 0 and xs[i].s_lo <= s <= xs[i].s_hi:
            return xs[i].route(s)
        return self.ell[int(t)], self.route0[int(t)]

    def repair_regions(self, t: int) -> List[KRepairThresholdRun]:
        return self.repair_runs[int(t)]

def _compile_q_latest_heads(index: CausalCutSuffixIndex, ell: Sequence[int], stats: Optional[RepairStats]=None) -> List[List[LatestOccurrenceHead]]:
    out: List[List[LatestOccurrenceHead]] = []
    for t, L0 in enumerate(ell):
        maxL = max(0, int(L0) - 1)
        xs = []
        L = 1
        while L <= maxL:
            e = index.latest_endpoint_for_suffix(t, L)
            if e is None:
                raise AssertionError(('matched suffix lost latest occurrence', t, L, L0))
            H = min(maxL, index.lcs_end(t, e))
            if H < L:
                raise AssertionError(('latest head lifetime', t, L, e, H))
            xs.append(LatestOccurrenceHead(t, L, H, int(e)))
            L = H + 1
        out.append(xs)
        if stats is not None:
            stats.q_latest_heads += len(xs)
            stats.q_latest_length_equiv += maxL
    return out

def _build_q_delete_from_latest_heads(ell: Sequence[int], heads: Sequence[Sequence[LatestOccurrenceHead]], stats: Optional[RepairStats]=None) -> List[List[AffineDeleteRun]]:
    out = [[] for _ in ell]
    for t, L0 in enumerate(ell):
        L = int(L0)
        if L <= 0:
            continue
        xs = [AffineDeleteRun(t, t, t, 0, 0, 0, -1)]
        for h in heads[t]:
            xs.append(AffineDeleteRun(t, t - h.L_hi, t - h.L_lo, -1, t, 0, h.endpoint))
        xs = _merge_affine_runs(xs)
        out[t] = xs
        if stats is not None:
            stats.q_delete_runs += len(xs)
            stats.q_delete_pair_equiv += L
    return out

def _pack_group_bits_to_python_ints(bits_t_d: torch.Tensor) -> List[int]:
    """bits_t_d: CPU uint8/bool [T,D] -> Python arbitrary-precision ints."""
    if bits_t_d.device.type != 'cpu':
        bits_t_d = bits_t_d.cpu()
    rows = bits_t_d.tolist()
    out: List[int] = []
    for row in rows:
        x = 0
        for j, b in enumerate(row):
            if int(b):
                x |= 1 << j
        out.append(x)
    return out

def _suffix_array_int(seq: Sequence[int]) -> List[int]:
    """Exact prefix-doubling suffix array for an integer sequence."""
    n = len(seq)
    if n == 0:
        return []
    vals = {v: i for i, v in enumerate(sorted(set(seq)))}
    rank = [vals[x] for x in seq]
    sa = list(range(n))
    tmp = [0] * n
    step = 1
    while True:
        sa.sort(key=lambda i: (rank[i], rank[i + step] if i + step < n else -1))
        tmp[sa[0]] = 0
        for z in range(1, n):
            a, b = (sa[z - 1], sa[z])
            ka = (rank[a], rank[a + step] if a + step < n else -1)
            kb = (rank[b], rank[b + step] if b + step < n else -1)
            tmp[b] = tmp[a] + int(ka != kb)
        rank, tmp = (tmp, rank)
        if rank[sa[-1]] == n - 1:
            break
        step <<= 1
    return sa

class _RangeMin:

    def __init__(self, values: Sequence[int]):
        size = 1
        while size < max(1, len(values)):
            size <<= 1
        self.size = size
        inf = 1 << 60
        tree = [inf] * (2 * size)
        for i, x in enumerate(values):
            tree[size + i] = int(x)
        for i in range(size - 1, 0, -1):
            tree[i] = min(tree[2 * i], tree[2 * i + 1])
        self.tree = tree

    def query(self, left: int, right: int) -> int:
        """min(values[left:right]); caller guarantees left < right."""
        left += self.size
        right += self.size
        ans = 1 << 60
        while left < right:
            if left & 1:
                ans = min(ans, self.tree[left])
                left += 1
            if right & 1:
                right -= 1
                ans = min(ans, self.tree[right])
            left >>= 1
            right >>= 1
        return int(ans)

class _SuffixLCE:
    """Exact LCP oracle for one integer sequence using suffix array + Kasai + RMQ."""

    def __init__(self, seq: Sequence[int]):
        self.seq = list(map(int, seq))
        n = len(self.seq)
        self.sa = _suffix_array_int(self.seq)
        rank = [0] * n
        for r, s in enumerate(self.sa):
            rank[s] = r
        self.rank = rank
        lcp_adj = [0] * max(0, n - 1)
        h = 0
        for i in range(n):
            r = rank[i]
            if r == n - 1:
                h = 0
                continue
            j = self.sa[r + 1]
            while i + h < n and j + h < n and (self.seq[i + h] == self.seq[j + h]):
                h += 1
            lcp_adj[r] = h
            if h:
                h -= 1
        self.rmq = _RangeMin(lcp_adj)

    def lcp(self, i: int, j: int) -> int:
        if i == j:
            return len(self.seq) - i
        ri, rj = (self.rank[i], self.rank[j])
        if ri > rj:
            ri, rj = (rj, ri)
        return self.rmq.query(ri, rj)

class _PayloadLCE:

    def __init__(self, baseline_labels: Sequence[Optional[int]], v_symbols: Sequence[int]):
        vals = sorted({int(x) for x in v_symbols} | {int(x) for x in baseline_labels if x is not None})
        mp = {x: i + 2 for i, x in enumerate(vals)}
        b = [1 if x is None else mp[int(x)] for x in baseline_labels]
        v = [mp[int(x)] for x in v_symbols]
        self.T = len(v)
        self.b_off = 0
        self.v_off = self.T + 1
        self.idx = _SuffixLCE(b + [0] + v + [self.T + len(vals) + 7])

    def lce(self, t: int, p: int) -> int:
        if t >= self.T or p >= self.T:
            return 0
        return min(self.idx.lcp(self.b_off + t, self.v_off + p), self.T - t, self.T - p)

class _DifferenceRS:
    """Sparse range sums of candidate hard payload score minus original hard baseline score."""

    def __init__(self, terms: Iterable[RepairTrackTerm], grad_y: torch.Tensor, v_bits: torch.Tensor, emb0_g: torch.Tensor, emb1_g: torch.Tensor, route_end: Sequence[int], stats: Optional[RepairStats]=None):
        T = int(grad_y.shape[0])
        self.T = T
        self.stats = stats
        v_symbols = _pack_group_bits_to_python_ints(v_bits)
        baseline_labels: List[Optional[int]] = []
        for t, r0 in enumerate(route_end):
            r = int(r0)
            baseline_labels.append(None if r < 0 else int(v_symbols[r + 1]))
        sem = _PayloadLCE(baseline_labels, v_symbols)
        grouped: Dict[int, List[Tuple[int, int]]] = {}
        raw = req = 0
        for z in terms:
            grouped.setdefault(int(z.shift), []).append((int(z.lo), int(z.hi)))
            raw += 1
            req += z.hi - z.lo + 1
        if stats is not None:
            stats.drs_raw_terms = raw
            stats.drs_unique_shifts = len(grouped)
            stats.drs_requested_points = req
        self.pos: Dict[int, List[int]] = {}
        self.pref: Dict[int, List[float]] = {}
        for shift, ivs in grouped.items():
            ivs.sort()
            merged: List[List[int]] = []
            for lo, hi in ivs:
                if not merged or lo > merged[-1][1] + 1:
                    merged.append([lo, hi])
                elif hi > merged[-1][1]:
                    merged[-1][1] = hi
            if stats is not None:
                stats.drs_merged_intervals += len(merged)
            mism: List[int] = []
            for lo, hi in merged:
                t = lo
                while t <= hi:
                    p = t + shift
                    if not 1 <= p < T:
                        raise AssertionError(('DRS payload OOB', shift, t, p, T))
                    if baseline_labels[t] is not None and baseline_labels[t] == v_symbols[p]:
                        z = max(1, min(sem.lce(t, p), hi - t + 1))
                        if stats is not None:
                            stats.drs_semantic_equal_skips += z
                        t += z
                    else:
                        mism.append(t)
                        t += 1
            if mism:
                tt = torch.tensor(mism, dtype=torch.long)
                pp = tt + int(shift)
                gy = grad_y.index_select(0, tt)
                cand_v = v_bits.index_select(0, pp).to(gy.dtype)
                cand = (cand_v * 2.0 - 1.0) * emb1_g
                base = torch.empty_like(cand)
                matched_mask = torch.tensor([int(route_end[t]) >= 0 for t in mism], dtype=torch.bool)
                if matched_mask.any():
                    br = torch.tensor([int(route_end[t]) + 1 if int(route_end[t]) >= 0 else 0 for t in mism], dtype=torch.long)
                    bv = v_bits.index_select(0, br).to(gy.dtype)
                    bmatched = (bv * 2.0 - 1.0) * emb1_g
                    base[:] = emb0_g
                    base[matched_mask] = bmatched[matched_mask]
                else:
                    base[:] = emb0_g
                vals = (gy * (cand - base)).sum(dim=-1).tolist()
            else:
                vals = []
            pr = [0.0]
            for x in vals:
                pr.append(pr[-1] + float(x))
            self.pos[shift] = mism
            self.pref[shift] = pr
            if stats is not None:
                stats.drs_materialized_mismatches += len(mism)

    def query(self, shift: int, lo: int, hi: int) -> float:
        if lo > hi:
            return 0.0
        xs = self.pos.get(int(shift), [])
        pr = self.pref.get(int(shift), [0.0])
        a = bisect.bisect_left(xs, lo)
        b = bisect.bisect_right(xs, hi)
        if self.stats is not None:
            self.stats.drs_queries += 1
        return pr[b] - pr[a]

def _contract_zero_surfaces(q: Sequence[int], k: Sequence[int], match_len: Sequence[int], surfaces: Sequence[ZeroBaselineSurface], v_bits: torch.Tensor, grad_y: torch.Tensor, emb0_g: torch.Tensor, emb1_g: torch.Tensor, D: int, stats: Optional[RepairStats]=None) -> torch.Tensor:
    T = len(q)
    out = torch.zeros((T, D), dtype=grad_y.dtype)
    if not surfaces:
        return out
    targets = sorted({z.target_symbol for z in surfaces})
    suffix = {c: torch.zeros((T + 1, D), dtype=grad_y.dtype) for c in targets}
    running = {c: torch.zeros((D,), dtype=grad_y.dtype) for c in targets}
    for t in range(T - 1, -1, -1):
        qt = int(q[t])
        if int(match_len[t]) == 0 and qt in running:
            running[qt] = running[qt] + grad_y[t]
        for c in targets:
            suffix[c][t] = running[c]
    by_key = {(z.k_symbol, z.bit): z for z in surfaces}
    for s, c0 in enumerate(k):
        c = int(c0)
        if s + 1 >= T:
            continue
        payload = (v_bits[s + 1].to(grad_y.dtype) * 2.0 - 1.0) * emb1_g
        diff = payload - emb0_g
        for j in range(D):
            z = by_key.get((c, j))
            if z is None:
                continue
            gsum = suffix[z.target_symbol][s + 1]
            out[s, j] = (gsum * diff).sum()
            if stats is not None:
                stats.k_surface_owner_evals += 1
    return out

def _flatten_terms(ir: RepairIR):
    for side in (ir.q_terms, ir.k_terms):
        for per_pos in side:
            for xs in per_pos:
                yield from xs

def _route_score(grad_t: torch.Tensor, v_bits: torch.Tensor, emb0_g: torch.Tensor, emb1_g: torch.Tensor, route_end: int) -> float:
    if route_end < 0:
        return float(torch.dot(grad_t, emb0_g).item())
    vidx = route_end + 1
    sign = v_bits[vidx].to(grad_t.dtype) * 2.0 - 1.0
    return float(torch.dot(grad_t, sign * emb1_g).item())

class _VecFenwick:

    def __init__(self, n: int, D: int, dtype: torch.dtype):
        self.n = n
        self.D = D
        self.bit = [torch.zeros((D + 1,), dtype=dtype) for _ in range(n + 1)]

    def add(self, i: int, v: torch.Tensor):
        i += 1
        while i <= self.n:
            self.bit[i] += v
            i += i & -i

    def prefix(self, i: int) -> torch.Tensor:
        z = torch.zeros_like(self.bit[0])
        while i > 0:
            z += self.bit[i]
            i -= i & -i
        return z

    def range(self, l: int, r: int) -> torch.Tensor:
        if l > r:
            return torch.zeros_like(self.bit[0])
        return self.prefix(r + 1) - self.prefix(l)

    def total(self) -> torch.Tensor:
        return self.prefix(self.n)

class _Fenwick:

    def __init__(self, n: int):
        self.n = n
        self.bit = [0.0] * (n + 1)

    def add(self, i: int, x: float):
        i += 1
        while i <= self.n:
            self.bit[i] += float(x)
            i += i & -i

    def prefix(self, i: int) -> float:
        s = 0.0
        while i > 0:
            s += self.bit[i]
            i -= i & -i
        return s

    def range_sum(self, lo: int, hi: int) -> float:
        if lo > hi:
            return 0.0
        return self.prefix(hi + 1) - self.prefix(lo)

    def total(self) -> float:
        return self.prefix(self.n)

class _KDeleteSurfaceSweep:

    def __init__(self, runs_by_t, grad_y, v_bits, emb0_g, emb1_g, baseline_score, score_fn):
        self.T = len(runs_by_t)
        self.D = int(grad_y.shape[1])
        self.gy = grad_y
        self.vb = v_bits
        self.e1 = emb1_g
        self.baseline = list(map(float, baseline_score))
        self.scalar_events = [[] for _ in range(self.T + 1)]
        self.diag_events = {}
        for t, xs in enumerate(runs_by_t):
            for z in xs:
                if z.end_a == 0:
                    delta = float(score_fn(t, z.end_b)) - self.baseline[t]
                    if delta:
                        self.scalar_events[z.s_lo].append((t, delta))
                        if z.s_hi + 1 <= self.T:
                            self.scalar_events[z.s_hi + 1].append((t, -delta))
                    continue
                Llo = z.len_a * z.s_lo + z.len_b
                Lhi = z.len_a * z.s_hi + z.len_b
                p_lo = z.end_a * z.s_lo + z.end_b + 1
                p_hi = z.end_a * z.s_hi + z.end_b + 1
                if z.end_a == 1 and min(Llo, Lhi) > 0 and (1 <= min(p_lo, p_hi)) and (max(p_lo, p_hi) < self.T):
                    c = z.end_b
                    ev = self.diag_events.setdefault(c, [[] for _ in range(self.T + 1)])
                    ev[z.s_lo].append((t, +1))
                    if z.s_hi + 1 <= self.T:
                        ev[z.s_hi + 1].append((t, -1))
                    continue
                for owner in range(z.s_lo, z.s_hi + 1):
                    _, r = z.route(owner)
                    delta = float(score_fn(t, r)) - self.baseline[t]
                    if delta:
                        self.scalar_events[owner].append((t, delta))
                        if owner + 1 <= self.T:
                            self.scalar_events[owner + 1].append((t, -delta))
        self.scalar_fw = _Fenwick(self.T)
        self.diag_fw = {c: _VecFenwick(self.T, self.D, grad_y.dtype) for c in self.diag_events}
        self.owner = -1

    def advance(self, s):
        if s != self.owner + 1:
            raise ValueError('K delete sweep must advance owner sequentially')
        self.owner = s
        for t, d in self.scalar_events[s]:
            self.scalar_fw.add(t, d)
        for c, ev in self.diag_events.items():
            fw = self.diag_fw[c]
            for t, sgn in ev[s]:
                vec = torch.empty((self.D + 1,), dtype=self.gy.dtype)
                vec[:self.D] = self.gy[t] * float(sgn)
                vec[self.D] = self.baseline[t] * float(sgn)
                fw.add(t, vec)

    def _embed(self, s, c):
        p = int(s) + int(c) + 1
        if not 1 <= p < self.T:
            raise AssertionError(('delete surface payload OOB', s, c, p, self.T))
        return (self.vb[p].to(self.gy.dtype) * 2.0 - 1.0) * self.e1

    def range_sum(self, lo, hi):
        if lo > hi:
            return 0.0
        val = float(self.scalar_fw.range_sum(lo, hi))
        s = self.owner
        for c, fw in self.diag_fw.items():
            z = fw.range(lo, hi)
            if torch.count_nonzero(z).item():
                val += float((z[:self.D] * self._embed(s, c)).sum() - z[self.D])
        return val

    def total(self):
        return self.range_sum(0, self.T - 1)

def _delete_affine_events(runs_by_t, baseline_score, score_fn, route_end, v_symbols):
    T = len(runs_by_t)
    events = [[] for _ in range(T + 1)]
    for t, xs in enumerate(runs_by_t):
        r0 = int(route_end[t])
        lab0 = None if r0 < 0 else int(v_symbols[r0 + 1])
        for z in xs:
            if z.end_a != 0:
                raise AssertionError(('Q-delete expects constant-endpoint surfaces', z))
            r = int(z.end_b)
            lab = None if r < 0 else int(v_symbols[r + 1])
            delta = 0.0 if lab == lab0 else float(score_fn(t, r)) - float(baseline_score[t])
            if delta:
                events[z.s_lo].append((t, delta))
                if z.s_hi + 1 <= T:
                    events[z.s_hi + 1].append((t, -delta))
    return events

class SurfaceVJP:
    """Pure numerical contraction.  No suffix/string/cut-envelope query is reachable from here."""

    @staticmethod
    def contract(ir: RepairIR, q: Sequence[int], k: Sequence[int], ell: Sequence[int], route: Sequence[int], v_bits: torch.Tensor, grad_y: torch.Tensor, emb0_g: torch.Tensor, emb1_g: torch.Tensor, D: int, stats: RepairStats):
        T = len(q)
        score_cache = [{} for _ in range(T)]

        def score(t, r):
            d = score_cache[t]
            r = int(r)
            if r not in d:
                d[r] = float(_route_score(grad_y[t], v_bits, emb0_g, emb1_g, r))
            return d[r]
        baseline = [score(t, int(route[t])) for t in range(T)]
        v_symbols = _pack_group_bits_to_python_ints(v_bits)

        class _DS:
            drs_raw_terms = drs_unique_shifts = drs_merged_intervals = drs_requested_points = 0
            drs_semantic_equal_skips = drs_materialized_mismatches = drs_queries = 0
        ds = _DS()
        drs = _DifferenceRS(_flatten_terms(ir), grad_y, v_bits, emb0_g, emb1_g, route, ds)
        qcred = torch.zeros((T, D), dtype=grad_y.dtype)
        events = _delete_affine_events(ir.q_delete_runs_by_t, baseline, score, route, v_symbols)
        fw = _Fenwick(T)
        for owner in range(T):
            for t, d in events[owner]:
                fw.add(t, d)
            base = fw.total()
            for j in range(D):
                val = base
                for z in ir.q_terms[owner][j]:
                    val += drs.query(z.shift, z.lo, z.hi) - fw.range_sum(z.lo, z.hi)
                    stats.q_overlay_queries += 1
                qcred[owner, j] = val
        ksweep = _KDeleteSurfaceSweep(ir.k_delete_runs_by_t, grad_y, v_bits, emb0_g, emb1_g, baseline, score)
        kcred = torch.zeros((T, D), dtype=grad_y.dtype)
        for owner in range(T):
            ksweep.advance(owner)
            base = ksweep.total()
            for j in range(D):
                val = base
                for z in ir.k_terms[owner][j]:
                    val += drs.query(z.shift, z.lo, z.hi) - ksweep.range_sum(z.lo, z.hi)
                    stats.k_overlay_queries += 1
                kcred[owner, j] = val
        kcred += _contract_zero_surfaces(q, k, ell, ir.k_zero_surfaces, v_bits, grad_y, emb0_g, emb1_g, D, None)
        for name in ('drs_raw_terms', 'drs_requested_points', 'drs_semantic_equal_skips', 'drs_materialized_mismatches', 'drs_queries'):
            setattr(stats, name, int(getattr(ds, name)))
        vcred = torch.zeros((T, D), dtype=grad_y.dtype)
        for t in range(T):
            r = int(route[t])
            if r < 0:
                continue
            owner = r + 1
            sign = v_bits[owner].to(grad_y.dtype) * 2.0 - 1.0
            vcred[owner] += grad_y[t] * (-2.0 * sign * emb1_g)
        return (qcred, kcred, vcred)

def _zero_baseline_surfaces(q: Sequence[int], k: Sequence[int], ell: Sequence[int], D: int) -> List[ZeroBaselineSurface]:
    unmatched = {int(q[t]) for t, L in enumerate(ell) if int(L) == 0}
    ksyms = set(map(int, k))
    out = []
    for c in sorted(ksyms):
        for j in range(D):
            tar = c ^ 1 << j
            if tar in unmatched:
                out.append(ZeroBaselineSurface(j, c, tar))
    return out

def _q_repair_terms_suffix_range(q, k, D, index: BiPositionSuffixIndex, stats: Optional[RepairStats]=None):
    """Exact Q repair skyline from the same bidirectional position-restricted suffix index."""
    T = len(q)
    out = [[[] for _ in range(D)] for _ in range(T)]
    for u in range(T):
        qu = int(q[u])
        for j in range(D):
            target = qu ^ 1 << j
            d = 0
            while u + d < T:
                best = index.direct_q_best_center(target, u, d)
                if best is None:
                    break
                p, L = best
                R = index.lcp_after_center(u, p)
                if R < d:
                    raise AssertionError(('direct Q right extent', u, j, d, p, L, R))
                out[u][j].append(RepairTrackTerm(p - u + 1, u + d, min(T - 1, u + R)))
                if stats is not None:
                    stats.q_direct_terms += 1
                d = R + 1
    return out

def _route_from_occ(index: BiPositionSuffixIndex, t: int, L: int, o: _OneBitOccurrence) -> Route:
    q0 = t - L + 1
    extra = index.lcs_before_center(q0, o.start)
    return int(L + extra), int(o.end)

def _compile_k_surface_conditioned(
    D: int,
    index: CausalCutSuffixIndex,
    kdel: KDeleteCutOracle,
    ell: Sequence[int],
    stats: Optional[RepairStats]=None,
) -> List[List[List[RepairTrackTerm]]]:
    """Exact K-repair compiler using surface thresholds plus Equality-Shadow H-ramp certificates.

    Constant threshold surfaces are still solved by one position-restricted one-mismatch query.
    The only important affine family is an H ramp L(s)=M-s (strict):

    * M > current endpoint r_t: Equality Shadow proves every p=M-e>0 repair impossible.  There is
      at most one p=0 saturation-boundary owner s=M-LCSuffix(Q[:t+1],K[:M+1]).
    * M == r_t: every p>0 repair is exactly a right-boundary square/run certificate in K.  All such
      K-only certificates are precompiled from maximal runs and queried by (M, owner interval).

    Any affine surface outside these proved cases uses the the one-threshold form one-query-per-owner fallback.
    """
    T = index.T
    best: List[List[Dict[int, Route]]] = [[{} for _ in range(D)] for _ in range(T)]
    run_index: Optional[_KRunRepairCertificateIndex] = None

    def record_route(t: int, s: int, j: int, cand: Route) -> None:
        old = best[int(s)][int(j)].get(int(t))
        if old is None or cand > old:
            best[int(s)][int(j)][int(t)] = (int(cand[0]), int(cand[1]))

    def record_occ(t: int, Lq: int, o: _OneBitOccurrence) -> None:
        record_route(t, int(o.mismatch_owner), int(o.bit), _route_from_occ(index, t, Lq, o))

    def record_shadow_event(t: int, s: int, j: int, e: int, d: int) -> None:
        u = int(t - d)
        if not (0 <= u < T and 0 <= s < T and 0 <= e < t):
            raise AssertionError(('shadow repair coordinate', t, s, j, e, d, u))
        actual_j = _onebit_index(int(index.q[u]) ^ int(index.k[s]), D)
        if actual_j != int(j):
            raise AssertionError(('shadow repair bit', t, s, j, e, d, u, actual_j))
        left = index.lcs_before_center(u, s)
        cand = (int(d + 1 + left), int(e))
        if cand <= kdel.route(t, s):
            raise AssertionError(('shadow repair failed threshold', t, s, j, cand, kdel.route(t, s)))
        record_route(t, s, j, cand)

    for t in range(T):
        if int(ell[t]) == 0:
            continue
        r0 = int(kdel.route0[t])
        for reg in kdel.repair_regions(t):
            if reg.len_a == 0:
                Lq = reg.threshold_length(reg.s_lo)
                if not 1 <= Lq <= t + 1:
                    continue
                if stats is not None:
                    stats.k_surface_queries += 1
                for o in index.one_bit_occurrences_filtered(t, Lq, reg.s_lo, reg.s_hi, D, stats):
                    record_occ(t, Lq, o)
                continue

            # Proven H-ramp family: strict threshold L(s)=M-s.
            if reg.strict and reg.len_a == -1:
                M = int(reg.len_b)
                if M > r0:
                    if stats is not None:
                        stats.k_h_ramp_boundary_queries += 1
                    # p=0 is the only possible repair.  The rightmost exact suffix ending at M
                    # determines the unique physical owner immediately to its left.
                    d = int(index.lcs_end(t, M))
                    s = int(M - d)
                    if reg.s_lo <= s <= reg.s_hi:
                        u = int(t - d)
                        if 0 <= s < T and 0 <= u < T:
                            j = _onebit_index(int(index.q[u]) ^ int(index.k[s]), D)
                            if j is not None:
                                if stats is not None:
                                    stats.k_h_ramp_boundary_hits += 1
                                record_shadow_event(t, s, int(j), M, d)
                    continue

                if M == r0:
                    # Current-endpoint H ramp.  Non-trivial repairs are exactly K-run certificates;
                    # no owner-wise variable-length one-mismatch queries remain in this branch.
                    if run_index is None:
                        run_index = _KRunRepairCertificateIndex(index, D, stats)
                    for c in run_index.query(M, reg.s_lo, reg.s_hi):
                        e = int(M - c.period)
                        d = int(e - c.owner)
                        if d < 0:
                            raise AssertionError(('run certificate negative depth', t, M, c, e, d))
                        record_shadow_event(t, c.owner, c.bit, e, d)
                    continue

            # Exact fallback for any affine surface not covered by the proved H-ramp normal form.
            for owner in range(reg.s_lo, reg.s_hi + 1):
                Lq = reg.threshold_length(owner)
                if not 1 <= Lq <= t + 1:
                    continue
                if stats is not None:
                    stats.k_surface_queries += 1
                    stats.k_surface_affine_owner_queries += 1
                    stats.k_h_ramp_fallback_owner_queries += 1
                for o in index.one_bit_occurrences_filtered(t, Lq, owner, owner, D, stats):
                    record_occ(t, Lq, o)

    out = [[[] for _ in range(D)] for _ in range(T)]
    for s in range(T):
        for j in range(D):
            items = sorted(best[s][j].items())
            if not items:
                continue
            lo = hi = items[0][0]
            shift = items[0][1][1] - lo + 1
            for t, r in items[1:]:
                sh = int(r[1]) - int(t) + 1
                if t == hi + 1 and sh == shift:
                    hi = t
                else:
                    out[s][j].append(RepairTrackTerm(shift, lo, hi))
                    lo = hi = t
                    shift = sh
            out[s][j].append(RepairTrackTerm(shift, lo, hi))
            if stats is not None:
                stats.k_surface_terms += len(out[s][j])
    return out

def _flip_credit_to_logit_grad(z: torch.Tensor, bits: torch.Tensor, flip_credit: torch.Tensor, tau: float, mode: str) -> torch.Tensor:
    """Map exact bit counterfactual credits to continuous pre-threshold logits."""
    orient = 1.0 - 2.0 * bits.to(dtype=z.dtype)
    l1_minus_l0 = orient * flip_credit.to(dtype=z.dtype, device=z.device)
    if mode == 'bernoulli':
        p = torch.sigmoid(z / tau)
        return p * (1.0 - p) / tau * l1_minus_l0
    if mode == 'identity':
        return l1_minus_l0
    raise ValueError(f'unknown credit_to_logit mode: {mode}')

