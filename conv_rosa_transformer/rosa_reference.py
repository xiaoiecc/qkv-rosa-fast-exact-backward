"""Hard n-bit QKV-ROSA standalone exact autograd layer.

Forward semantics are unchanged. Backward computes exact finite one-bit hard-routing
counterfactual VJP credits. Repair uses an adaptive exact compiler:
- shared sparse/diagonal one-hole bridges when materialisation is cheaper;
- surface/run-certified compilation for large dense cases.

The large-case compiler keeps the one-threshold surface normal form, then eliminates the
important affine H-ramp owner scan using the exact Equality-Shadow decomposition proved for this compiler: off-current ramps have at most one saturation-boundary repair; current-endpoint ramps are
reported from K-only right-boundary square certificates generated by maximal runs.  Certificates
are joined to H surfaces by a static (anchor point, owner interval) range index.  Any affine family
outside the proved H-ramp form retains an exact one-query-per-owner fallback.
The file contains only runtime/support code reachable from the exported API.
"""
